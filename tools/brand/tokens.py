# contrast audit
def lum(h):
    h = h.lstrip('#'); c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def cr(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True); return (la + 0.05) / (lb + 0.05)
checks = [('light', LIGHT, ['text', 'text-2', 'text-3', 'accent-text', 'success', 'warning', 'danger', 'info'], ['bg', 'surface', 'surface-2']),
          ('dark', DARK, ['text', 'text-2', 'text-3', 'accent-text', 'success', 'warning', 'danger', 'info'], ['bg', 'surface', 'surface-2'])]
out = {}
for mode, P, fgs, bgs in checks:
    for fg in fgs:
        for bg in bgs:
            r = cr(P[fg], P[bg]); out['%s %s/%s' % (mode, fg, bg)] = round(r, 2)
            if r < 4.5: print('FAIL', mode, fg, 'on', bg, round(r, 2))
out['ink on signal'] = round(cr('#0A0A0A', '#FF4405'), 2)
out['white on ink'] = round(cr('#FFFFFF', '#0A0A0A'), 2)
json.dump(out, open(os.path.join(ROOT, 'brand/tokens/contrast.json'), 'w'), indent=1)
print('tokens ok; min light', min(v for k, v in out.items() if k.startswith('light')), 'min dark', min(v for k, v in out.items() if k.startswith('dark')))
