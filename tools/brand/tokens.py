def dtcg():
    col = lambda d: {k: {'$value': v, '$type': 'color'} for k, v in d.items()}
    return {
        'brand': col(BRAND),
        'color': {'light': col(LIGHT), 'dark': col(DARK)},
        'font': {'family': {k: {'$value': v, '$type': 'fontFamily'} for k, v in FONT.items()}},
        'type': {k: {'$type': 'typography', '$value': {'fontFamily': '{font.family.%s}' % ('mono' if k == 'mono' else 'sans'),
                  'fontSize': '%dpx' % s, 'lineHeight': '%dpx' % lh, 'fontWeight': w, 'letterSpacing': '%sem' % t}}
                 for k, (s, lh, w, t) in TYPE.items()},
        'space': {str(i): {'$value': '%dpx' % v, '$type': 'dimension'} for i, v in enumerate(SPACE)},
        'radius': {k: {'$value': '%dpx' % v, '$type': 'dimension'} for k, v in RADIUS.items()},
        'shadow': {'light': {k: {'$value': v, '$type': 'shadow'} for k, v in SHADOW_L.items()},
                   'dark': {k: {'$value': v, '$type': 'shadow'} for k, v in SHADOW_D.items()}},
        'motion': {k: {'$value': v, '$type': 'duration' if v.endswith('ms') else 'cubicBezier'} for k, v in MOTION.items()},
    }

def css():
    L = []
    L.append('/* Halo design tokens — generated by tools/brand/tokens.py. Do not edit by hand. */')
    root = [':root {', '  color-scheme: light dark;']
    root += ['  --brand-%s: %s;' % (k, v) for k, v in BRAND.items()]
    root += ['  --font-%s: %s;' % (k, v) for k, v in FONT.items()]
    for k, (s, lh, w, t) in TYPE.items():
        root.append('  --type-%s: %s %dpx/%dpx var(--font-%s);' % (k, w, s, lh, 'mono' if k == 'mono' else 'sans'))
        root.append('  --track-%s: %sem;' % (k, t))
    root += ['  --space-%d: %dpx;' % (i, v) for i, v in enumerate(SPACE)]
    root += ['  --radius-%s: %dpx;' % (k, v) for k, v in RADIUS.items()]
    root += ['  --dur-%s: %s;' % (k, v) for k, v in MOTION.items() if v.endswith('ms')]
    root += ['  --%s: %s;' % (k, v) for k, v in MOTION.items() if not v.endswith('ms')]
    root.append('}')
    L += root
    light = ['  --%s: %s;' % (k, v) for k, v in LIGHT.items()] + ['  --shadow-%s: %s;' % (k, v) for k, v in SHADOW_L.items()]
    dark = ['  --%s: %s;' % (k, v) for k, v in DARK.items()] + ['  --shadow-%s: %s;' % (k, v) for k, v in SHADOW_D.items()]
    L += [':root, :root[data-theme="light"] {'] + light + ['}', ':root[data-theme="light"] { color-scheme: light; }']
    L += ['@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', '    color-scheme: dark;'] + ['  ' + x for x in dark] + ['  }', '}']
    L += [':root[data-theme="dark"] {', '  color-scheme: dark;'] + dark + ['}']
    return '\n'.join(L) + '\n'

